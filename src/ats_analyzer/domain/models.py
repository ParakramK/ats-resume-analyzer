"""Validated domain models shared by every layer.

Pydantic models carry data across boundaries (parsers -> scoring -> UI ->
reports). They contain no behavior and import nothing from infrastructure,
Streamlit, or LangChain.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, SecretStr

from ats_analyzer.config import DEFAULT_TIMEOUT_SECONDS
from ats_analyzer.domain.scoring_rules import METHODOLOGY_NOTE


class _StrictModel(BaseModel):
    """Base class forbidding unexpected keys — typos fail fast."""

    model_config = ConfigDict(extra="forbid")


class ParsedResume(_StrictModel):
    """Structured result of parsing an uploaded resume document."""

    text: str
    filename: str
    file_format: Literal["pdf", "docx", "txt"]
    pages: int = 1
    word_count: int = 0
    emails: list[str] = Field(default_factory=list)
    phones: list[str] = Field(default_factory=list)
    links: list[str] = Field(default_factory=list)
    skills: list[str] = Field(default_factory=list)  # canonical lexicon hits
    sections: dict[str, str] = Field(default_factory=dict)  # normalized name -> text


class JobRequirements(_StrictModel):
    """Requirements extracted (locally, or optionally by AI) from a job description."""

    title: str = ""
    responsibilities: list[str] = Field(default_factory=list)
    required_skills: list[str] = Field(default_factory=list)
    preferred_skills: list[str] = Field(default_factory=list)
    keywords: list[str] = Field(default_factory=list)
    min_years_experience: int | None = None
    education: list[str] = Field(default_factory=list)
    certifications: list[str] = Field(default_factory=list)


class CategoryScore(_StrictModel):
    """One scoring category: raw score, its weight, and supporting notes."""

    key: str
    label: str
    weight: float  # percentage points (e.g. 30.0)
    score: float  # raw category score, 0-100
    contribution: float  # score * weight / 100
    applicable: bool = True  # False => excluded from the overall score
    notes: list[str] = Field(default_factory=list)


class AtsResult(_StrictModel):
    """Deterministic ATS compatibility result. Never generated by an LLM."""

    overall: float  # 0-100
    categories: list[CategoryScore]
    matched_required: list[str] = Field(default_factory=list)
    missing_required: list[str] = Field(default_factory=list)
    matched_preferred: list[str] = Field(default_factory=list)
    missing_preferred: list[str] = Field(default_factory=list)
    matched_keywords: list[str] = Field(default_factory=list)
    missing_keywords: list[str] = Field(default_factory=list)
    strengths: list[str] = Field(default_factory=list)
    weaknesses: list[str] = Field(default_factory=list)
    methodology: str = METHODOLOGY_NOTE


class BulletSuggestion(_StrictModel):
    original: str
    suggested: str


class SkillGap(_StrictModel):
    skill: str
    note: str


class AiFeedback(_StrictModel):
    """Structured AI advice. Suggestions only — never fabricated facts."""

    assessment: str = ""
    strengths: list[str] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)
    bullet_suggestions: list[BulletSuggestion] = Field(default_factory=list)
    skill_gaps: list[SkillGap] = Field(default_factory=list)


class ProviderConfig(_StrictModel):
    """What the user configured in the sidebar. Keys live in session memory only."""

    provider_id: Literal["openai", "gemini", "mistral", "compatible"]
    model: str = ""
    api_key: SecretStr | None = None
    base_url: str | None = None
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS


class AnalysisMetadata(_StrictModel):
    generated_at: str  # local ISO timestamp
    scoring_engine: str
    ai_provider: str = "none"  # human-readable label, never credentials
    ai_model: str = ""
    weights: dict[str, float] = Field(default_factory=dict)


class AnalysisReport(_StrictModel):
    """Complete analysis container used by the UI and both exporters."""

    resume_filename: str
    job_title: str
    ats: AtsResult
    ai_feedback: AiFeedback | None = None
    local_recommendations: list[str] = Field(default_factory=list)
    metadata: AnalysisMetadata
